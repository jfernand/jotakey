"""Generate jotakey.pretty/TouchPad_D10mm.kicad_mod: a 10 mm touch electrode with the ISSS logo
(the lightning bolt of the ISSS design system's favicon) cut out of its copper.

KiCad pads cannot contain holes, so the electrode is a custom pad made of two simple polygons.
A vertical line through the bolt crosses its outline exactly twice; the disc is split along that
line, and each half follows the bolt's outline on its side. The union of the two halves is the
disc minus the bolt. Under the solder mask the bolt then shows as bare laminate, and the
footprint fills the same outline with silkscreen, so the logo also shows under a dark mask that
hides the difference between copper and laminate. That is the only silkscreen on the electrode.

Run from this directory:  python3 make_touchpad.py
"""
import math
import pathlib

# ISSS favicon.svg, viewBox 0 0 48 48 (y grows downwards, as in KiCad).
BOLT = [(28, 2), (10, 26), (22, 26), (14, 46), (42, 20), (28, 20), (40, 2)]
RADIUS = 5.0           # electrode radius, mm
BOLT_HEIGHT = 7.0      # height of the cut-out, mm
CUT_X = 24.0           # vertical split line in logo units; crosses the bolt outline twice
ANCHOR = (-4.2, 0.0)   # pad origin: must lie in copper (the disc centre is inside the bolt)
ARC_SEGMENTS = 96

scale = BOLT_HEIGHT / 44.0           # the bolt spans y = 2..46
cx, cy = 26.0, 24.0                  # centre of the bolt's bounding box -> disc centre


def to_mm(p):
    return ((p[0] - cx) * scale, (p[1] - cy) * scale)


def crossing(a, b, x):
    """Point where segment a-b crosses the vertical line at x (logo units)."""
    t = (x - a[0]) / (b[0] - a[0])
    return (x, a[1] + t * (b[1] - a[1]))


# The split line crosses edge (28,2)-(10,26) at the top and edge (14,46)-(42,20) at the bottom.
top = crossing(BOLT[0], BOLT[1], CUT_X)
bottom = crossing(BOLT[3], BOLT[4], CUT_X)

cut_x = (CUT_X - cx) * scale
edge_y = math.sqrt(RADIUS**2 - cut_x**2)


def arc(start_deg, end_deg):
    pts = []
    for i in range(ARC_SEGMENTS + 1):
        a = math.radians(start_deg + (end_deg - start_deg) * i / ARC_SEGMENTS)
        pts.append((RADIUS * math.cos(a), RADIUS * math.sin(a)))
    return pts


theta_bottom = math.degrees(math.atan2(edge_y, cut_x))      # ~93.6 deg (KiCad: +y is down)
theta_top = math.degrees(math.atan2(-edge_y, cut_x)) + 360  # ~266.4 deg

left = ([(cut_x, -edge_y), to_mm(top), to_mm(BOLT[1]), to_mm(BOLT[2]), to_mm(BOLT[3]),
         to_mm(bottom), (cut_x, edge_y)]
        + arc(theta_bottom, theta_top)[1:-1])
right = ([(cut_x, -edge_y), to_mm(top), to_mm(BOLT[0]), to_mm(BOLT[6]), to_mm(BOLT[5]),
          to_mm(BOLT[4]), to_mm(bottom), (cut_x, edge_y)]
         + arc(theta_bottom, theta_top - 360)[1:-1])


def poly(points):
    rel = " ".join(f"(xy {x - ANCHOR[0]:.4f} {y - ANCHOR[1]:.4f})" for x, y in points)
    return f"      (gr_poly (pts {rel}) (width 0) (fill yes))\n"


def silk_bolt():
    """The bolt itself, filled, on the top silkscreen: exactly over the copper cut-out."""
    pts = " ".join(f"(xy {x:.4f} {y:.4f})" for x, y in (to_mm(p) for p in BOLT))
    return f'  (fp_poly (pts {pts}) (stroke (width 0) (type solid)) (fill yes) (layer "F.SilkS"))\n'


def circle(layer, r, width, fill="none"):
    return (f'  (fp_circle (center 0 0) (end {r} 0) (stroke (width {width}) (type solid)) '
            f'(fill {fill}) (layer "{layer}"))\n')


text = f'''(footprint "TouchPad_D10mm"
  (version 20240108)
  (generator "make_touchpad.py")
  (layer "F.Cu")
  (descr "Capacitive touch electrode, 10 mm diameter, F.Cu under solder mask (no mask opening), with the ISSS logo (lightning bolt, {BOLT_HEIGHT:g} mm tall) cut out of the copper. Generated by lib/make_touchpad.py. Per ST AN4312 3.5.6: no other copper within 2 mm on F.Cu (4-5 mm recommended); a 10 % hatched ground on B.Cu.")
  (attr smd exclude_from_bom exclude_from_pos_files)
  (tags "touch capacitive electrode TSC ISSS logo")
  (property "Reference" "REF**" (at 0 -6.5 0) (layer "F.Fab") (hide yes)
    (effects (font (size 1 1) (thickness 0.15))))
  (property "Value" "TouchPad_D10mm" (at 0 6.5 0) (layer "F.Fab")
    (effects (font (size 1 1) (thickness 0.15))))
  (pad "1" smd custom (at {ANCHOR[0]} {ANCHOR[1]}) (size 0.4 0.4) (layers "F.Cu")
    (options (clearance outline) (anchor circle))
    (primitives
{poly(left)}{poly(right)}    )
  )
{silk_bolt()}{circle("F.Fab", RADIUS, 0.1)}{circle("F.CrtYd", 5.9, 0.05)})
'''

pathlib.Path(__file__).with_name("jotakey.pretty").joinpath("TouchPad_D10mm.kicad_mod").write_text(text)
print(f"bolt {scale * 32:.2f} x {BOLT_HEIGHT} mm; split at x = {cut_x:.3f} mm; "
      f"crossings y = {to_mm(top)[1]:.3f}, {to_mm(bottom)[1]:.3f} mm")
